# frozen_string_literal: true

# Slipway Markdown twins (ADR 0006): a raw Markdown copy of every page, at the page's address with
# `.md` (`/about.html` is `/about.md`, `/guide/` is `/guide/index.md`), so an agent can read the source
# instead of the HTML.
#
# In Actions mode Jekyll loads this file as a plugin and writes each twin at build: the source file's
# bytes with the front matter removed, Liquid not evaluated. Classic Pages runs no plugins, so
# `npm run twins` (tools/twins/twins.rb) uses the same code to write one stub page per source, which
# includes the source with `include_relative`; the author commits the stubs.

require "fileutils"

module Slipway
  module Twins
    # The same front matter rule as Jekyll::Document.
    FRONT_MATTER = %r!\A(---\s*\n.*?\n?)^((---|\.\.\.)\s*$\n?)!m.freeze
    MARKDOWN_EXTENSIONS = %w(.md .markdown .mkdown .mkdn .mkd).freeze
    STUB_SUFFIX = ".twin.html"
    # Layouts that write most of the page themselves (post lists, tag and author pages, the 404 page). Their
    # source is a title and an intro, not the page, so they get no twin.
    LISTING_LAYOUTS = %w(home archive tags author not-found translation-status).freeze

    module_function

    # The twin's address for a page address.
    def twin_url(url)
      return "#{url}index.md" if url.end_with?("/")
      url.sub(%r!\.html?\z!, "") + ".md"
    end

    # The source without its front matter: everything after the line break that ends the closing
    # `---` line, blank lines kept, as the classic stub gives it.
    def body(source)
      match = %r!\A---[ \t]*\r?\n.*?^(---|\.\.\.)[ \t]*(\r?\n|\z)!m.match(source)
      match ? match.post_match : source
    end

    # Pages and collection documents written from a Markdown file with front matter, except on a
    # listing layout. A file without front matter needs no twin: Jekyll already copies it as is
    # (ADR 0006, decision 5).
    def sources(site)
      docs = site.collections.values.flat_map(&:docs).select(&:write?)
      (site.pages + docs).select do |page|
        next false if LISTING_LAYOUTS.include?(page.data["layout"])
        path = source_path(site, page)
        MARKDOWN_EXTENSIONS.include?(File.extname(path).downcase) && File.file?(path) &&
          path.start_with?(File.join(site.source, "")) && FRONT_MATTER.match?(File.read(path, :encoding => "bom|utf-8"))
      end
    end

    def source_path(site, page)
      page.is_a?(::Jekyll::Document) ? page.path : site.in_source_dir(page.relative_path)
    end

    def relative(site, path)
      path.delete_prefix(File.join(site.source, "")).tr("\\", "/")
    end

    # Where the stub for a source sits. `include_relative` cannot climb with `..`, so the stub is in the
    # source's folder; a source in a folder Jekyll does not publish (`_posts/`, a collection) gets its
    # stub in the parent of that folder, named after the path: `_posts/2026-01-02-a.md` gives
    # `posts-2026-01-02-a.twin.html`.
    def stub_path(source)
      parts = source.split("/")
      hidden = parts.index { |part| part.start_with?("_") }
      return source.sub(%r!\.[^./]+\z!, STUB_SUFFIX) if hidden.nil?
      name = parts[hidden..].join("-").delete_prefix("_").sub(%r!\.[^./]+\z!, STUB_SUFFIX)
      (parts[0...hidden] + [name]).join("/")
    end

    # The stub page for one source. Liquid strips the front matter: the first two `---` and the text
    # between them, removed once, then the first line break, which ends the closing `---` line.
    def stub(source, url)
      include = source.delete_prefix(File.dirname(stub_path(source)) + "/")
      <<~STUB
        ---
        # Generated by `npm run twins` (ADR 0006). Do not edit; run it again when #{source} moves or its address changes.
        layout: null
        permalink: #{url}
        twin_of: #{source}
        sitemap: false
        search: false
        ---
        {%- capture sl_twin %}{% include_relative #{include} %}{% endcapture -%}
        {%- capture sl_nl %}
        {% endcapture -%}
        {%- assign sl_fm = sl_twin | split: "---" -%}
        {%- assign sl_fm = sl_fm[1] | prepend: "---" | append: "---" -%}
        {{ sl_twin | remove_first: sl_fm | remove_first: sl_nl -}}
      STUB
    end

    # Every stub a site needs, as { stub path => text }, sorted by path.
    def stubs(site)
      result = {}
      sources(site).each do |page|
        source = relative(site, source_path(site, page))
        path = stub_path(source)
        raise "twins: #{source} and #{result[path][:source]} both need the stub #{path}" if result.key?(path)
        result[path] = { :source => source, :text => stub(source, twin_url(page.url)) }
      end
      result.sort.to_h { |path, entry| [path, entry[:text]] }
    end
  end
end

if defined?(Jekyll::Generator)
  module Slipway
    module Twins
      # One twin, written as is: no layout and no Liquid.
      class TwinFile < ::Jekyll::StaticFile
        def initialize(site, url, content)
          super(site, site.source, File.dirname(url), File.basename(url))
          @url = url
          @content = content
        end

        def modified?
          true
        end

        def destination(dest)
          @site.in_dest_dir(dest, @url)
        end

        def write(dest)
          path = destination(dest)
          FileUtils.mkdir_p(::File.dirname(path))
          ::File.write(path, @content)
          true
        end
      end

      # Actions mode: twins are generated at build, so they cannot go stale, and committed stubs are dropped.
      class Generator < ::Jekyll::Generator
        safe false
        priority :lowest

        def generate(site)
          site.pages.reject! { |page| page.data.key?("twin_of") }
          Twins.sources(site).each do |page|
            url = Twins.twin_url(page.url)
            site.static_files << TwinFile.new(site, url, Twins.body(File.read(Twins.source_path(site, page), :encoding => "bom|utf-8")))
            # The head links the twin from page.slipway_twin (head.html).
            page.data["slipway_twin"] = url
          end
        end
      end
    end
  end
end
